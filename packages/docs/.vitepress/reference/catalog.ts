function includesAny<T>(values: T[], selected?: T[]): boolean {
  return !selected?.length || selected.some((value) => values.includes(value));
}

export function filterCatalogEntries(
  entries: ReferenceCatalogEntry[] = referenceCatalog,
  filters: ReferenceCatalogFilters = {},
): ReferenceCatalogEntry[] {
  const query = filters.query?.trim().toLocaleLowerCase();

  return entries.filter((entry) => {
    const searchable = [
      entry.title,
      entry.summary,
      entry.family,
      entry.primaryTask,
      ...entry.tags,
      ...(entry.aliases ?? []),
      ...entry.symbols.map((symbol) => symbol.name),
      ...publicContractSymbols
        .filter((symbol) => symbol.href.startsWith(entry.path))
        .map((symbol) => symbol.name),
    ]
      .filter(Boolean)
      .join(' ')
      .toLocaleLowerCase();

    return (
      (!query || searchable.includes(query)) &&
      (!filters.kinds?.length || filters.kinds.includes(entry.kind)) &&
      (!filters.families?.length || (!!entry.family && filters.families.includes(entry.family))) &&
      includesAny(entry.tags, filters.tags) &&
      includesAny(entry.surfaces, filters.surfaces) &&
      includesAny(entry.packages, filters.packages) &&
      (!filters.statuses?.length || filters.statuses.includes(entry.status))
    );
  });
}

export function sortCatalogEntries(
  entries: ReferenceCatalogEntry[] = referenceCatalog,
): ReferenceCatalogEntry[] {
  return [...entries].sort((left, right) => left.title.localeCompare(right.title));
}

export function groupCatalogEntries(
  entries: ReferenceCatalogEntry[] = referenceCatalog,
  group: ReferenceCatalogGroup = 'kind',
): Record<string, ReferenceCatalogEntry[]> {
  const grouped: Record<string, ReferenceCatalogEntry[]> = {};

  for (const entry of entries) {
    const keys =
      group === 'package'
        ? entry.packages
        : group === 'surface'
          ? entry.surfaces
          : [entry[group] ?? 'other'];

    for (const key of keys) {
      (grouped[key] ??= []).push(entry);
    }
  }

  return grouped;
}

export function getReferenceSymbols(
  entries: ReferenceCatalogEntry[] = referenceCatalog,
): ReferenceSymbol[] {
  return [
    ...entries.flatMap((entry) =>
      entry.symbols.map((symbol) => ({
        ...symbol,
        status: symbol.status ?? entry.status,
      })),
    ),
    ...publicContractSymbols,
  ];
}

